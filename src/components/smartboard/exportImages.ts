import type { SlideImage } from './imageStore'

/** `topicId:slideKey` → a filesystem-safe filename for /public/decks/. */
const fileFor = (key: string) => `${key.replace(':', '__').replace(/[^a-zA-Z0-9_-]/g, '-')}.webp`

function triggerDownload(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = name
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 4000)
}

function dataUrlToBlob(dataUrl: string): Blob {
  const [head, b64] = dataUrl.split(',')
  const mime = /data:(.*?);base64/.exec(head)?.[1] ?? 'image/webp'
  const bin = atob(b64)
  const bytes = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i)
  return new Blob([bytes], { type: mime })
}

/**
 * Export every locally-uploaded image to a downloadable `.webp` file plus a
 * ready-to-commit `imageManifest.ts`. Entries that already point to `/decks/`
 * (already committed) are carried through unchanged.
 */
export function exportImagesToRepo(images: Record<string, SlideImage>) {
  const keys = Object.keys(images).sort()
  if (keys.length === 0) {
    alert('No images to export yet — upload a centre image on a slide first.')
    return
  }

  const manifest: Record<string, SlideImage> = {}
  let fileCount = 0

  for (const key of keys) {
    const img = images[key]
    if (img.src.startsWith('data:')) {
      const name = fileFor(key)
      triggerDownload(dataUrlToBlob(img.src), name)
      fileCount++
      manifest[key] = { ...img, src: `/decks/${name}` }
    } else {
      // already a committed /decks/ path — keep as-is
      manifest[key] = img
    }
  }

  const body = Object.entries(manifest)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n')
  const ts = `import type { SlideImage } from '../components/smartboard/imageStore'

/** Auto-generated by "Save images to repo". Commit this file + /public/decks/. */
export const IMAGE_MANIFEST: Record<string, SlideImage> = {
${body}
}
`
  triggerDownload(new Blob([ts], { type: 'text/plain' }), 'imageManifest.ts')

  alert(
    `Exported ${fileCount} image file(s) + imageManifest.ts to your Downloads.\n\n` +
      `Next:\n` +
      `1. Move the .webp files into  public/decks/\n` +
      `2. Replace  src/content/imageManifest.ts  with the downloaded one\n` +
      `3. git add -A && git commit && git push\n\n` +
      `After that the images show on any PC that pulls the repo.`,
  )
}
