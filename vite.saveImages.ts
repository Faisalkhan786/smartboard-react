import fs from 'node:fs'
import path from 'node:path'
import type { Plugin } from 'vite'

/**
 * Dev-only endpoint: POST /__save-images
 *
 * The "Save images to repo" button posts the deck's current images here. The
 * Node side (which, unlike the browser, can write to disk) then:
 *   1. writes each locally-uploaded image to  public/decks/<topicId>__<slideKey>.webp
 *   2. rewrites  src/content/imageManifest.ts  to reference them
 *
 * After this you only need:  git add -A && git commit && git push
 * Runs only while `npm run dev` is active — exactly when you author decks.
 */
export function saveImagesPlugin(): Plugin {
  return {
    name: 'smartboard-save-images',
    apply: 'serve',
    configureServer(server) {
      server.middlewares.use('/__save-images', (req, res) => {
        if (req.method !== 'POST') {
          res.statusCode = 405
          res.end('Method Not Allowed')
          return
        }

        let body = ''
        req.on('data', (chunk) => (body += chunk))
        req.on('end', () => {
          try {
            const { images } = JSON.parse(body) as { images: Record<string, SlideImageLike> }
            const root = server.config.root
            const decksDir = path.join(root, 'public', 'decks')
            fs.mkdirSync(decksDir, { recursive: true })

            const manifest: Record<string, SlideImageLike> = {}
            let written = 0

            let removed = 0
            for (const key of Object.keys(images).sort()) {
              const img = images[key]
              if (img?.deleted) {
                // tombstone — remove the committed file and omit from the manifest
                try {
                  fs.unlinkSync(path.join(decksDir, fileFor(key)))
                  removed++
                } catch {
                  /* file already gone */
                }
                continue
              }
              if (typeof img?.src === 'string' && img.src.startsWith('data:')) {
                const file = fileFor(key)
                const b64 = img.src.slice(img.src.indexOf(',') + 1)
                fs.writeFileSync(path.join(decksDir, file), Buffer.from(b64, 'base64'))
                written++
                manifest[key] = { ...img, src: `/decks/${file}` }
              } else if (typeof img?.src === 'string') {
                // already a committed /decks/ path — carry through
                manifest[key] = img
              }
            }

            const manifestPath = path.join(root, 'src', 'content', 'imageManifest.ts')
            fs.writeFileSync(manifestPath, renderManifest(manifest), 'utf8')

            res.statusCode = 200
            res.setHeader('Content-Type', 'application/json')
            res.end(JSON.stringify({ ok: true, written, removed, total: Object.keys(manifest).length }))
          } catch (err) {
            res.statusCode = 500
            res.setHeader('Content-Type', 'application/json')
            res.end(JSON.stringify({ ok: false, error: String(err) }))
          }
        })
      })
    },
  }
}

interface SlideImageLike {
  src: string
  deleted?: boolean
  [k: string]: unknown
}

/** `topicId:slideKey` → filesystem-safe filename for /public/decks/. */
function fileFor(key: string) {
  return `${key.replace(':', '__').replace(/[^a-zA-Z0-9_-]/g, '-')}.webp`
}

function renderManifest(manifest: Record<string, SlideImageLike>) {
  const body = Object.entries(manifest)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n')
  return `import type { SlideImage } from '../components/smartboard/imageStore'

/**
 * Auto-generated by the "Save images to repo" button. Do not hand-edit the
 * entries below — re-run the button instead. Commit this file together with
 * the matching files in /public/decks/.
 */
export const IMAGE_MANIFEST: Record<string, SlideImage> = {
${body}
}
`
}
